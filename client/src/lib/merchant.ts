/**
 * שם בית העסק בקובץ מגיע מקוצר ולעיתים עם רווחים מיותרים או סימני שאלה.
 * הנרמול מאפשר לזהות שאותו בית עסק חוזר בין חודשים ובין כרטיסים.
 *
 * הפונקציה יושבת במודול נפרד ולא ב-parseExcel כדי שמסכים שאינם מייבאים
 * קבצים לא ייגררו איתם את ספריית האקסל הכבדה.
 */
export function normalizeMerchant(name: string): string {
  return name
    .toLowerCase()
    .replace(/[?*"'׳״]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}
